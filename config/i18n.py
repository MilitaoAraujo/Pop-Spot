def t(chave: str, **kwargs) -> str:
    lang = idioma()
    tabela = STRINGS.get(lang) or STRINGS["pt"]
    texto = tabela.get(chave) or STRINGS["pt"].get(chave, chave)
    if kwargs:
        try:
            return texto.format(**kwargs)
        except Exception:
            return texto
    return texto
